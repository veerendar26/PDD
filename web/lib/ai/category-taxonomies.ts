// Lookup helper: resolves any user-selected category or alias into a canonical taxonomy
export function resolveCategoryTaxonomy(categoryName: string): CategoryTaxonomy | null {
  if (!categoryName) return null;
  const normalized = categoryName.toLowerCase().trim();

  // Direct key lookup
  if (CATEGORY_TAXONOMIES[normalized]) {
    return CATEGORY_TAXONOMIES[normalized];
  }

  // Alias lookup
  for (const tax of Object.values(CATEGORY_TAXONOMIES)) {
    if (tax.aliases.some((alias) => normalized.includes(alias) || alias.includes(normalized))) {
      return tax;
    }
  }

  return null;
}
